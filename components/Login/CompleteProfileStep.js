import React, { useState } from 'react';
import { View, Text, TextInput, TouchableOpacity, StyleSheet, ActivityIndicator } from 'react-native';
import { useSetRecoilState } from 'recoil';
import { authAtom } from '../../recoil/atoms/authAtom';
import { profileAtom } from '../../recoil/atoms/profileAtom';
import { signupWithFirebaseOtpBff } from '../../services/bff/authBff';
import { CheckCircle2, User, Mail } from 'lucide-react-native';
import { handleGlobalError } from '../../utils/errorHandler';

const CompleteProfileStep = ({ phoneNumber, firebaseIdToken, onAuthSuccess }) => {
  const [firstName, setFirstName] = useState('');
  const [lastName, setLastName] = useState('');
  const [email, setEmail] = useState('');
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');
  const [focusedField, setFocusedField] = useState(null);

  const setAuth = useSetRecoilState(authAtom);
  const setProfile = useSetRecoilState(profileAtom);

  const handleCompleteProfile = async () => {
    if (!firstName.trim()) {
      setError('First name is required');
      return;
    }

    if (email.trim() && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email.trim())) {
      setError('Please enter a valid email address');
      return;
    }

    setLoading(true);
    setError('');

    try {
      // Generate a random password - crypto.getRandomValues is not available in React Native Hermes
      const chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789';
      let randomPart = '';
      for (let i = 0; i < 32; i++) {
        randomPart += chars.charAt(Math.floor(Math.random() * chars.length));
      }
      const autoGeneratedPassword = randomPart + 'Aa1@';
      // If email is empty, we can generate a placeholder one tied to their phone number to satisfy Postgres unique constraints
      const finalEmail = email.trim() ? email.trim() : `${phoneNumber.replace('+', '')}@ngfreshfoods.com`;

      const backendResponse = await signupWithFirebaseOtpBff({
        idToken: firebaseIdToken,
        firstName: firstName.trim(),
        lastName: lastName.trim(),
        email: finalEmail,
        password: autoGeneratedPassword,
        phoneNumber: phoneNumber
      });

      if (backendResponse.success) {
        await onAuthSuccess?.();
        setAuth((prev) => ({
          ...prev,
          isAuthenticated: true,
        }));
        setProfile(backendResponse.data.profile);
      } else {
        throw new Error(backendResponse.error.message || "Failed to create profile");
      }
    } catch (err) {
      console.log("Profile Completion Error: ", err);
      const errorMessage = handleGlobalError(err, "Profile Completion");
      setError(errorMessage);
    } finally {
      setLoading(false);
    }
  };

  return (
    <View style={styles.container}>
      {/* Typography */}
      <Text style={styles.headingPlayfair}>Almost there</Text>
      
      <Text style={styles.subheading}>
        We just need a few details to setup your fresh foods account
      </Text>

      {/* Error Message Box */}
      {error ? (
        <View style={styles.errorContainer}>
          <Text style={styles.errorText}>{error}</Text>
        </View>
      ) : null}

      <View style={styles.formContainer}>
        {/* Name Row */}
        <View style={styles.inputRow}>
          {/* First Name Input */}
          <View style={[styles.inputGroup, { flex: 1 }]}>
            <View style={[
              styles.inputContainer, 
              focusedField === 'firstName' ? styles.inputContainerFocused : null,
              error && !firstName.trim() ? styles.inputContainerError : null
            ]}>
              <User size={18} color={focusedField === 'firstName' ? '#1E2B24' : '#4a5c52'} style={styles.inputIcon} />
              <TextInput
                style={styles.textInput}
                placeholder="First Name"
                placeholderTextColor="#7a8a80"
                value={firstName}
                onChangeText={(text) => { setFirstName(text); setError(''); }}
                onFocus={() => setFocusedField('firstName')}
                onBlur={() => setFocusedField(null)}
                editable={!loading}
                autoCapitalize="words"
              />
            </View>
          </View>

          {/* Last Name Input */}
          <View style={[styles.inputGroup, { flex: 1 }]}>
            <View style={[
              styles.inputContainer,
              focusedField === 'lastName' ? styles.inputContainerFocused : null
            ]}>
              <User size={18} color={focusedField === 'lastName' ? '#1E2B24' : '#4a5c52'} style={styles.inputIcon} />
              <TextInput
                style={styles.textInput}
                placeholder="Last Name"
                placeholderTextColor="#7a8a80"
                value={lastName}
                onChangeText={setLastName}
                onFocus={() => setFocusedField('lastName')}
                onBlur={() => setFocusedField(null)}
                editable={!loading}
                autoCapitalize="words"
              />
            </View>
          </View>
        </View>

        {/* Email Input */}
        <View style={styles.inputGroup}>
          <View style={[
            styles.inputContainer,
            focusedField === 'email' ? styles.inputContainerFocused : null
          ]}>
            <Mail size={18} color={focusedField === 'email' ? '#1E2B24' : '#4a5c52'} style={styles.inputIcon} />
            <TextInput
              style={styles.textInput}
              placeholder="Email Address (Optional)"
              placeholderTextColor="#7a8a80"
              value={email}
              onChangeText={setEmail}
              onFocus={() => setFocusedField('email')}
              onBlur={() => setFocusedField(null)}
              editable={!loading}
              keyboardType="email-address"
              autoCapitalize="none"
            />
          </View>
        </View>
      </View>

      {/* Sticky Bottom Action Button */}
      <TouchableOpacity 
        style={[styles.mainButton, loading || !firstName.trim() ? styles.buttonDisabled : null]}
        onPress={handleCompleteProfile}
        disabled={loading || !firstName.trim()}
        activeOpacity={0.8}
      >
        {loading ? (
          <ActivityIndicator color="#FFFFFF" size="small" />
        ) : (
          <>
            <CheckCircle2 color="#FFFFFF" size={20} strokeWidth={3} />
            <Text style={styles.mainButtonText}>Create Account</Text>
          </>
        )}
      </TouchableOpacity>
    </View>
  );
};

